-- Safely convert description to JSONB if it was previously TEXT
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 
        FROM information_schema.columns 
        WHERE table_name = 'products' AND column_name = 'description' AND data_type = 'text'
    ) THEN
        ALTER TABLE products ALTER COLUMN description TYPE JSONB USING CASE 
            WHEN description IS NULL OR description = '' THEN '{}'::jsonb 
            WHEN description LIKE '{%' THEN description::jsonb 
            ELSE jsonb_build_object('en', description, 'ua', description) 
        END;
    END IF;
END $$;

